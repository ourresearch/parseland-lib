"""oxjob #2239 phase 2, round 8d: three mechanisms the fresh-draw junk tripwire failed at 92bc1d9.

1. Cochrane protocols: the Cochrane Library's template sentences "This is a protocol for a Cochrane Review (...). The
   objectives are as follows:" in front of every protocol's objectives are site text, not the abstract.
2. LaTeX accents left in back-matter text by a page's MathJax source ("Universit\\(\\acute {e}\\) Libre de Bruxelles"):
   rendered to the accented letter in acknowledgments, funding and reference text.
3. A funding text that runs on into other declaration sections ("Patient consent", "Provenance and peer review",
   "Data availability"): the funding statement ends at the line that is only another section's label.
"""
from parseland_lib.back_matter import before_other_section, tex_letters
from parseland_lib.not_abstract import clean_abstract
from parseland_lib.parse import _statement, parse_page

# ---------------------------------------------------------------- 1. Cochrane's protocol template

OBJECTIVES = ("To evaluate the impact of the different GnRHa protocols as adjuncts to ovulation stimulation in women "
              "undergoing assisted reproduction.")


def test_cochrane_protocol_template_cut():
    text = "This is a protocol for a Cochrane Review (Intervention). The objectives are as follows:\n" + OBJECTIVES
    assert clean_abstract(text) == OBJECTIVES


def test_cochrane_protocol_template_cut_any_review_type_on_one_line():
    text = "This is a protocol for a Cochrane Review (Diagnostic test accuracy). The objectives are as follows: " \
           + OBJECTIVES
    assert clean_abstract(text) == OBJECTIVES


def test_cochrane_older_protocol_template_cut():
    text = "This is the protocol for a review and there is no abstract. The objectives are as follows:\n" + OBJECTIVES
    assert clean_abstract(text) == OBJECTIVES


def test_protocol_abstract_of_a_trial_kept():
    # look-alike: an author's own abstract of a trial protocol
    text = ("This is a protocol for a randomised controlled trial of exercise in older adults. The objectives are as "
            "follows: to compare falls over twelve months between the two arms, and to measure adherence.")
    assert clean_abstract(text) == text


def test_cochrane_template_without_objectives_line_kept():
    # look-alike: the first sentence alone, inside an author's text, is not the template
    text = ("This is a protocol for a Cochrane Review (Intervention) that we registered in 2019; the review itself "
            "is reported here and assesses the effects of exercise on falls in older adults living at home.")
    assert clean_abstract(text) == text


# ---------------------------------------------------------------- 2. LaTeX accents in back-matter text

def test_math_mode_accent_rendered():
    assert tex_letters("students to come to Universit\\(\\acute {e}\\) Libre de Bruxelles") == \
        "students to come to Université Libre de Bruxelles"


def test_math_mode_accents_of_each_kind():
    assert tex_letters("Universit\\(\\grave{a}\\) di Roma, K\\(\\ddot{o}\\)ln, Montr\\(\\'e\\)al") == \
        "Università di Roma, Köln, Montréal"


def test_text_mode_accents_rendered_when_braced():
    assert tex_letters("Pad\\'{e}, B\\\"{o}hm, Cari\\~{n}ena, Bo\\c{t}, Andr{\\'e}, {\\v{S}}koda") == \
        "Padé, Böhm, Cariñena, Boţ, André, Škoda"


def test_escaped_apostrophes_and_quotes_kept():
    # look-alikes: outside math an unbraced \' or \" is an escaped apostrophe or quote, not an accent
    for text in ("Spinoza\\'s treatise", "l\\'effet de serre", "the authors\\' contributions",
                 'the \\"Hello\\" project', "don\\'t"):
        assert tex_letters(text) == text


def test_lone_letter_in_math_loses_its_wrapper():
    assert tex_letters("Compressed \\(k\\)-means for large-scale clustering") == \
        "Compressed k-means for large-scale clustering"


def test_real_math_kept():
    # look-alikes: math that is not one letter stays as the page printed it
    for text in ("measurement of the top quark mass in the \\(t\\bar{t}\\rightarrow \\) dilepton channel",
                 "Approximation of \\(1/x\\) by exponential sums", "The \\(C^{*}\\)-algebra generated by an isometry",
                 "the group \\(\\mathrm {GU}_{B}(2)\\)", "a mean of \\(\\bar{t}\\) seconds",
                 "Supported by grant 12\\34 of the Foundation", "no backslash at all"):
        assert tex_letters(text) == text


def test_statement_renders_accents():
    assert _statement("We thank the Universit\\(\\acute {e}\\) Libre de Bruxelles for support.") == \
        "We thank the Université Libre de Bruxelles for support."


# ---------------------------------------------------------------- 3. a funding text that runs on into other sections

NO_GRANT = ("This research received no specific grant from any finding agency in the public, commercial or not for "
            "profit sectors.")


def test_funding_ends_at_other_section_label_lines():
    text = (NO_GRANT + "\nPatient consent\nObtained.\nThe study was approved by the Ethics Committee of our Centre."
            "\nProvenance and peer review\nNot commissioned; externally peer reviewed.")
    assert before_other_section(text) == NO_GRANT


def test_funding_ends_at_data_availability_label():
    text = ("This work was supported by the Korea Institute of Oriental Medicine (No. KSN2121211).\n"
            "Availability of data and materials\nThe datasets used are available from the corresponding author.")
    assert before_other_section(text) == "This work was supported by the Korea Institute of Oriental Medicine " \
                                         "(No. KSN2121211)."


def test_funding_lines_that_are_not_labels_kept():
    # look-alikes: a sentence that opens with a section word, a funder's name, a funding label
    for text in (NO_GRANT + "\nConsent was obtained from all participants before the study began.",
                 "Funded by Ethicon Inc.\nEthicon Endo-Surgery",
                 "Supported by the National Institutes of Health.\nFunding\nGrant R01 CA123456",
                 "Data availability\nThe data are available on request."):  # a label on the first line is not a run-on
        assert before_other_section(text) == text


def test_acknowledgments_not_cut_at_label_lines():
    text = "We thank our colleagues.\nData availability\nThe data are available on request."
    assert _statement(text) == text


def test_auctoresonline_funding_section_with_span_wrapped_labels():
    """auctoresonline.org's template prints BMJ's declaration labels inside the Funding block as
    <p><span><strong>Label</strong></span></p> (cut from a stored page); its parser reads the whole block."""
    head = '<meta property="og:url" content="https://auctoresonline.org/article/x">'
    body = ('<div class="article-details"><div class="u-list"><ul><li>Gabriella Fizzotti<sup>1</sup></li></ul>'
            '<p><sup>1</sup>Spinal Unit, Pavia, Italy.</p></div></div>'
            '<div class="article-desc">'
            '<h4 class="article-det-header" id="conclusion">Conclusion</h4>'
            '<div class="parent-cls"><p><span>We conclude.</span></p></div>'
            '<h4 class="article-det-header" id="funding">Funding</h4><div class="parent-cls" data-for="funding">'
            f'<p><span>{NO_GRANT}</span></p>'
            '<p><span><strong>Declaration of conflicting interests </strong></span></p>'
            '<p><span>The authors declared no potential conflicts of interest with respect to the research.</span></p>'
            '<p><span><strong>Patient consent</strong></span></p><p><span>Obtained.</span></p>'
            '<p><span><strong>Provenance and peer review</strong></span></p>'
            '<p><span>Not commissioned; externally peer reviewed.</span></p></div>'
            '<h4 id="references">References</h4></div>')
    out = parse_page(f"<html><head>{head}</head><body>{body}</body></html>".encode(), "doi",
                     "https://auctoresonline.org/article/x")
    assert out["funding_statement"] == NO_GRANT
